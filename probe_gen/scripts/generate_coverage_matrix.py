#!/usr/bin/env python3
"""Generate a CVE coverage matrix for one app.

Reads ``experimental/android_*_enriched.jsonl``, filters to CVEs whose CWEs
overlap the app's archetype CWE focus, and matches them against a supplied
set of invariants + probes (loaded from JSON, typically generated by the
pipeline runner). Writes ``probe_coverage_matrix.md`` and ``.json``.

This script is the offline analog of Phase 1.5: it lets us see what the
coverage gap looks like for a given (app, invariants) pair without running
the full pipeline. Useful for the pilot's coverage audit step.

Usage::

    # Quick gap-only view: no invariants supplied, all CWEs in scope are gaps.
    python probe_gen/scripts/generate_coverage_matrix.py --app openvpn

    # With a supplied invariants/probes JSON:
    python probe_gen/scripts/generate_coverage_matrix.py \\
        --app openvpn \\
        --invariants probe_gen/runs/<id>/invariants.json \\
        --probes probe_gen/runs/<id>/probes.json
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

# Allow running this script directly: add repo root to sys.path so `probe_gen`
# resolves as a package without requiring an editable install.
_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from probe_gen.pipeline.archetypes import get_archetype, list_known_apps  # noqa: E402
from probe_gen.pipeline.coverage import (  # noqa: E402
    build_coverage_matrix,
    filter_by_archetype_cwes,
    load_enriched_dataset,
    render_coverage_matrix_md,
)
from probe_gen.pipeline.models import Invariant, Probe  # noqa: E402


def _load_invariants(path: Optional[Path]) -> list[Invariant]:
    if path is None or not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    return [Invariant.from_dict(d) for d in data]


def _load_probes(path: Optional[Path]) -> list[Probe]:
    if path is None or not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    return [Probe.from_dict(d) for d in data]


def main(argv: Optional[list[str]] = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    p.add_argument(
        "--app", required=True, help="App name (must be tagged in archetypes.py)."
    )
    p.add_argument(
        "--invariants",
        default=None,
        help="Path to invariants JSON (list of Invariant.to_dict()). "
        "Default: empty (every relevant CVE shows as gap).",
    )
    p.add_argument(
        "--probes",
        default=None,
        help="Path to probes JSON (list of Probe.to_dict()). Default: empty.",
    )
    p.add_argument(
        "--enriched-dir",
        default=None,
        help="Directory containing android_*_enriched.jsonl files. "
        "Default: <repo_root>/experimental.",
    )
    p.add_argument(
        "--out",
        default=None,
        help="Output directory (default: probe_gen/runs/coverage_<app>_<ts>).",
    )
    args = p.parse_args(argv)

    if args.app not in list_known_apps():
        print(
            f"[coverage] app {args.app!r} not in archetypes.py — known: "
            f"{', '.join(list_known_apps())}",
            file=sys.stderr,
        )
        return 2

    script_dir = Path(__file__).resolve().parent
    repo_root = script_dir.parent.parent
    enriched_dir = (
        Path(args.enriched_dir) if args.enriched_dir else (repo_root / "experimental")
    )
    enriched_paths = sorted(enriched_dir.glob("android_*_enriched.jsonl"))
    if not enriched_paths:
        print(f"[coverage] no enriched .jsonl files in {enriched_dir}", file=sys.stderr)
        return 2

    if args.out:
        out_dir = Path(args.out)
    else:
        ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        out_dir = repo_root / "probe_gen" / "runs" / f"coverage_{args.app}_{ts}"
    out_dir.mkdir(parents=True, exist_ok=True)

    archetype = get_archetype(args.app)
    all_cves = load_enriched_dataset(enriched_paths)
    relevant = filter_by_archetype_cwes(all_cves, archetype.cwe_focus)

    invariants = _load_invariants(Path(args.invariants) if args.invariants else None)
    probes = _load_probes(Path(args.probes) if args.probes else None)

    matrix = build_coverage_matrix(relevant, invariants, probes)
    md = render_coverage_matrix_md(args.app, matrix)

    md_path = out_dir / "probe_coverage_matrix.md"
    json_path = out_dir / "probe_coverage_matrix.json"
    md_path.write_text(md, encoding="utf-8")
    json_path.write_text(
        json.dumps(
            {
                "schema_version": 1,
                "app": args.app,
                "archetype": archetype.name,
                "archetype_cwe_focus": archetype.cwe_focus,
                "enriched_sources": [str(p) for p in enriched_paths],
                "total_android_cves_loaded": len(all_cves),
                "total_relevant_cves": len(relevant),
                "rows": [r.to_dict() for r in matrix],
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    covered = sum(1 for r in matrix if not r.gap)
    print(
        f"[coverage] app={args.app} archetype={archetype.name} "
        f"cves_in_scope={len(relevant)} covered={covered} gaps={len(matrix)-covered}",
        file=sys.stderr,
    )
    print(f"[coverage] md={md_path}", file=sys.stderr)
    print(f"[coverage] json={json_path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
