TEMPLATES = {
    "test_access_control.py": ACCESS_TEMPLATE,
    "test_availability.py": AVAILABILITY_TEMPLATE,
    "test_confidentiality.py": CONFIDENTIALITY_TEMPLATE,
    "test_integrity.py": INTEGRITY_TEMPLATE,
}


def main() -> None:
    args = parse_args()
    project_root = Path(__file__).resolve().parent.parent
    app_dir = project_root / "apps" / args.app_name

    if not app_dir.is_dir():
        sys.exit(f"App directory not found: {app_dir}")

    try:
        metadata = load_metadata(app_dir)
    except Exception as exc:
        sys.exit(str(exc))

    created: list[str] = []
    skipped: list[str] = []

    for filename, template in TEMPLATES.items():
        path = app_dir / filename
        if write_file(path, template, args.force):
            created.append(filename)
        else:
            skipped.append(filename)

    print(f"✓ Probes ready for {args.app_name}")
    if created:
        print(f"  created: {', '.join(created)}")
    if skipped:
        print(f"  skipped (exists): {', '.join(skipped)}")

    warnings: list[str] = []
    if not metadata.get("package_name"):
        warnings.append(
            "package_name missing in metadata.json (required for app probes)"
        )
    if metadata.get("container_names") is None:
        warnings.append("container_names missing in metadata.json (set to [] if none)")

    for warning in warnings:
        print(f"⚠️  {warning}")


if __name__ == "__main__":
    main()
