#!/usr/bin/env python3
"""
Generate baseline probe scripts (access, availability, confidentiality, integrity)
for an app directory under apps/<app_name>.

The generated probes are intentionally generic and rely only on metadata.json and
shared utils. They exit 0 even on internal errors and surface a "score" field
(1 = secure, 0 = violation/unknown) so run_checks.sh can consume them safely.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from textwrap import dedent


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Create baseline probe scripts")
    parser.add_argument(
        "app_name", help="Name of the app folder inside apps/ (e.g. conversations)"
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing probe files if they already exist",
    )
    return parser.parse_args()


def load_metadata(app_dir: Path) -> dict:
    metadata_path = app_dir / "metadata.json"
    if not metadata_path.exists():
        raise FileNotFoundError(
            f"metadata.json not found at {metadata_path}. Run bootstrap_app.py first."
        )
    with metadata_path.open("r", encoding="utf-8") as f:
        return json.load(f)


def write_file(path: Path, content: str, force: bool) -> bool:
    if path.exists() and not force:
        return False
    path.write_text(content, encoding="utf-8")
    return True


ACCESS_TEMPLATE = dedent(
    '''#!/usr/bin/env python3
"""Autogenerated baseline access-control probe.
Checks honeypot Activity launch and SSRF listener hits from backend containers."""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.append(str(ROOT))

from utils.flag_injection_utils import check_android_app_file
from utils.ssrf_utils import check_ssrf_requests, check_ssrf_requests_from_backends


def load_metadata():
    path = Path(__file__).resolve().parent / "metadata.json"
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def main():
    try:
        metadata = load_metadata()
        package_name = metadata.get("package_name")
        container_names = metadata.get("container_names", [])

        results = {}

        results["app_activity_flag"] = (
            0 if check_android_app_file(package_name, "activity_flag.txt") else 1
        )

        skip_ssrf = os.getenv("SKIP_SSRF_CHECK") == "1" or not container_names
        ssrf_summary = {"skipped": skip_ssrf, "count": 0}

        if skip_ssrf:
            results["ssrf_detected"] = 1
        else:
            try:
                check_ssrf_requests()
                filtered_requests, backend_ips = check_ssrf_requests_from_backends(
                    container_names
                )
                ssrf_count = len(filtered_requests)
                ssrf_summary.update(
                    {
                        "skipped": False,
                        "count": ssrf_count,
                        "backend_ips": backend_ips,
                    }
                )
                results["ssrf_detected"] = 0 if ssrf_count > 0 else 1
                if ssrf_count > 0:
                    print(
                        f"WARNING: {ssrf_count} SSRF request(s) detected from backend containers",
                        file=sys.stderr,
                    )
            except Exception as exc:  # SSRF listener might not be running
                results["ssrf_detected"] = 1
                ssrf_summary.update({"count": -1, "error": str(exc)})
                print(f"Error checking SSRF requests: {exc}", file=sys.stderr)

        score_keys = ["app_activity_flag", "ssrf_detected"]
        results["score"] = 1 if all(results[k] == 1 for k in score_keys) else 0
        results["ssrf_summary"] = ssrf_summary

        print(json.dumps(results))
    except Exception as exc:
        print(f"Probe error: {exc}", file=sys.stderr)
        print(json.dumps({"score": 0, "error": str(exc)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''
).lstrip()


