"""Phase-scoped backend image swap for server-side zero-day tasks.

Most zero-day tasks are *app-side*: Phase 1 (vulnerable) and Phase 2 (secure)
differ only in the Android APK / app codebase, and the victim backend is the
same pinned image in both phases (see ``evaluation.task_bundle.ZerodayBundle``).

A *server-side* task is one whose ``fix.patch`` lives in the backend server
(e.g. wallabag's PHP core, home-assistant-core's Python), not the app. The APK
is byte-identical across phases; what differs is the backend. The harness has no
way to ``git apply`` a patch into a prebuilt backend image, so these tasks were
historically scored off-harness.

This module implements the **image-swap** strategy: for a server-side task the
bundle carries a prebuilt *vulnerable* image and a prebuilt *patched* image
(produced by ``scripts/build_zeroday_backend_images.sh``). Before each phase's
backend bring-up the runner writes a Docker Compose *override* that repoints the
backend service at the phase-appropriate image, and exports a ``COMPOSE_FILE``
env var so every ``docker compose`` invocation in that phase (the reset ``down
-v`` and the ``start_runtime.sh`` ``up --build``) layers the override on top of
the app's base compose file.

The override uses the Compose Spec ``!reset`` tag to drop any ``build:`` section
on the target service, so a locally-built service (wallabag) uses our prebuilt
image instead of rebuilding from its Dockerfile. ``!reset`` requires Docker
Compose v2.24.4+ (Feb 2024); older versions must fall back to a full override
that redeclares the service.

Nothing here runs Docker — it only writes the override file and computes the
``COMPOSE_FILE`` value. The runner threads the returned env dict into the
compose subprocesses.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, Optional

from utils.logger import logger

OVERRIDE_FILENAME = ".mcb-zeroday-backend.override.yml"

# Runner phase-slug -> server_side.images key. Mirrors
# evaluation.task_bundle / _phase_slug_for_output_dir: phase1_original ->
# "vulnerable", phase2_patched -> "secure".
_PHASE_TO_IMAGE_KEY = {"vulnerable": "vulnerable", "secure": "secure"}


def _base_compose_filename(app_dir: Path) -> Optional[str]:
    """Return the app's base compose filename (.yml or .yaml), if present."""
    for name in ("docker-compose.yml", "docker-compose.yaml",
                 "compose.yml", "compose.yaml"):
        if (app_dir / name).exists():
            return name
    return None


def _render_override(service: str, image: str) -> str:
    """Render a minimal compose override repointing ``service`` at ``image``.

    ``build: !reset null`` drops any build section merged from the base file so
    compose uses the prebuilt ``image`` verbatim (no rebuild). Resetting a key
    the base service does not define is a no-op, so this is safe for both
    build-based (wallabag) and image-based (home-assistant) services.
    """
    return (
        "# Generated by evaluation.backend_image_swap — do not edit by hand.\n"
        "# Phase-scoped backend image swap for a server-side zero-day task.\n"
        "services:\n"
        f"  {service}:\n"
        "    build: !reset null\n"
        f"    image: {image}\n"
    )


def write_phase_override(
    app_dir: Path, service: str, image: str, phase_slug: str
) -> Dict[str, str]:
    """Write the phase override into ``app_dir`` and return compose env vars.

    Args:
        app_dir: The app directory containing the base compose file — the cwd
            for the compose ``down``/``up`` subprocesses.
        service: Compose service to repoint (e.g. ``wallabag``,
            ``home-assistant-server``).
        image: Fully-qualified image ref to use for this phase.
        phase_slug: ``vulnerable`` or ``secure`` (for logging only).

    Returns:
        ``{"COMPOSE_FILE": "<base>:<override>"}`` to merge into the subprocess
        environment. Empty dict (and no file written) if no base compose file
        exists — a server-side swap is meaningless without one, so the caller
        should treat that as a configuration error upstream.
    """
    base = _base_compose_filename(app_dir)
    if base is None:
        logger.warning(
            "backend_image_swap: no base compose file in %s; skipping override",
            app_dir,
        )
        return {}

    override_path = app_dir / OVERRIDE_FILENAME
    override_path.write_text(_render_override(service, image))
    logger.info(
        "backend_image_swap: phase=%s service=%s -> image=%s (override=%s)",
        phase_slug, service, image, override_path.name,
    )
    # COMPOSE_FILE is ':'-separated and resolved relative to the compose
    # project dir (cwd == app_dir), so bare filenames are correct here.
    return {"COMPOSE_FILE": f"{base}:{OVERRIDE_FILENAME}"}


def clear_phase_override(app_dir: Path) -> None:
    """Remove a previously written override file (idempotent)."""
    override_path = app_dir / OVERRIDE_FILENAME
    try:
        override_path.unlink()
    except FileNotFoundError:
        pass


def image_key_for_phase(phase_slug: str) -> Optional[str]:
    """Map a runner phase slug to the ``server_side.images`` key it needs."""
    return _PHASE_TO_IMAGE_KEY.get(phase_slug)
